function formatOrganDonorValue(value, copy = getCopy()) {
  if (value === true || value === "true") {
    return copy.organDonorYes || uiTranslations.en.organDonorYes;
  }
  if (value === false || value === "false") {
    return copy.organDonorNo || uiTranslations.en.organDonorNo;
  }
  return "N/A";
}

function formatGenderValue(value, copy = getCopy()) {
  return (
    {
      male: copy.labelMale || "Male",
      female: copy.labelFemale || "Female",
      non_binary: copy.labelNonBinary || "Non-binary",
      prefer_not_to_say: copy.labelPreferNot || "Prefer not to say"
    }[cleanText(value)] || "N/A"
  );
}

function formatBirthDate(value) {
  const normalized = cleanText(value);
  if (!normalized) {
    return "N/A";
  }

  try {
    return new Date(`${normalized}T00:00:00`).toLocaleDateString(root.lang || "en", {
      year: "numeric",
      month: "long",
      day: "numeric"
    });
  } catch (error) {
    return normalized;
  }
}

function resolveField(record, field) {
  const sourceLanguage = cleanText(record.default_language || "en").slice(0, 2).toLowerCase();
  if (sourceLanguage === "es") {
    return cleanText(record[`${field}_source`] || record[`${field}_es`] || record[`${field}_en`]);
  }
  return cleanText(record[`${field}_source`] || record[`${field}_en`] || record[`${field}_es`]);
}

function resolveNotes(record) {
  const raw = resolveField(record, "notes");
  return raw
    .split(/\r?\n+/)
    .map((item) => item.replace(/^[-*]\s*/, "").trim())
    .filter(Boolean);
}

function digitsOnly(value) {
  return cleanText(value).replace(/\D/g, "");
}

function formatLocalPhone(value) {
  const digits = digitsOnly(value);
  if (!digits) {
    return "";
  }
  if (digits.length <= 3) {
    return digits;
  }
  if (digits.length <= 6) {
    return `${digits.slice(0, 3)}-${digits.slice(3)}`;
  }
  if (digits.length <= 10) {
    return `${digits.slice(0, 3)}-${digits.slice(3, 6)}-${digits.slice(6)}`;
  }
  return `${digits.slice(0, 3)}-${digits.slice(3, 6)}-${digits.slice(6, 10)} ${digits.slice(10)}`;
}

function formatPhone(value, fallbackCode = "+1") {
  const normalized = cleanText(value);
  if (!normalized) {
    return "";
  }

  if (normalized.startsWith("+")) {
    const compact = normalized.replace(/[().\s-]+/g, "");
    const match = compact.match(/^(\+\d{1,3})(\d+)$/);
    if (match) {
      return `${match[1]} ${formatLocalPhone(match[2])}`.trim();
    }
    return normalized;
  }

  return `${fallbackCode} ${formatLocalPhone(normalized)}`.trim();
}

function sanitizeTel(phone) {
  return cleanText(phone).replace(/[^\d+]/g, "");
}

