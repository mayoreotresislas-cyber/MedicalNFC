async function requestTranslation(sourceLanguage, targetLanguage, fields) {
  const response = await fetch(`${config.supabaseUrl}/functions/v1/${config.translationFunctionName}`, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      apikey: config.supabaseAnonKey,
      Authorization: `Bearer ${config.supabaseAnonKey}`
    },
    body: JSON.stringify({
      sourceLanguage,
      targetLanguage,
      fields
    })
  });

  const payload = await response.json().catch(() => null);
  if (!response.ok) {
    throw new Error(payload?.error || "Translation failed");
  }

  return payload?.fields || fields;
}

async function ensureUiCopy(lang) {
  if (staticUiLanguages.has(lang)) {
    return uiTranslations[lang] || uiTranslations.en;
  }

  if (state.uiCopyCache[lang]) {
    return state.uiCopyCache[lang];
  }

  if (state.uiCopyPending[lang]) {
    return state.uiCopyPending[lang];
  }

  if (!config.translationFunctionName || !hasSupabaseConfig()) {
    state.uiCopyCache[lang] = uiTranslations.en;
    return state.uiCopyCache[lang];
  }

  const sourceFields = Object.fromEntries(Object.entries(uiTranslations.en).map(([key, value]) => [key, cleanText(value)]));
  const request = requestTranslation("en", lang, sourceFields)
    .then((fields) => {
      const translated = {
        ...uiTranslations.en,
        ...fields
      };
      state.uiCopyCache[lang] = translated;
      delete state.uiCopyPending[lang];
      return translated;
    })
    .catch((error) => {
      console.warn(`Public interface translation failed for ${lang}`, error);
      delete state.uiCopyPending[lang];
      state.uiCopyCache[lang] = uiTranslations.en;
      return state.uiCopyCache[lang];
    });

  state.uiCopyPending[lang] = request;
  return request;
}

function detectIdentifier() {
  const url = new URL(window.location.href);
  const querySlug = url.searchParams.get("slug");
  if (querySlug) {
    return decodeURIComponent(querySlug);
  }

  const segments = url.pathname.split("/").filter(Boolean);
  const medIndex = segments.findIndex((segment) => segment.toLowerCase() === "med");
  if (medIndex >= 0 && segments[medIndex + 1]) {
    return decodeURIComponent(segments[medIndex + 1]);
  }

  return cleanText(config.defaultSlug);
}

