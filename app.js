function applyCopy() {
  const copy = getCopy();
  textNodes.forEach((node) => {
    const key = node.dataset.i18n;
    node.textContent = copy[key] || uiTranslations.en[key] || "";
  });
  placeholderNodes.forEach((node) => {
    const key = node.dataset.i18nPlaceholder;
    node.setAttribute("placeholder", copy[key] || uiTranslations.en[key] || "");
  });
  ariaNodes.forEach((node) => {
    const key = node.dataset.i18nAriaLabel;
    node.setAttribute("aria-label", copy[key] || uiTranslations.en[key] || "");
  });
  languageSelect.value = state.lang;
  syncFlagSelect(languageSelect);
  updateRequestReasonOptions(copy);
  setRequestSubmitting(state.requestSubmitting);

  if (!staticUiLanguages.has(state.lang) && !state.uiCopyCache[state.lang]) {
    const activeLang = state.lang;
    ensureUiCopy(activeLang).then(() => {
      if (state.lang === activeLang) {
        applyCopy();
      }
    });
  }
}

async function translateFields(record, targetLanguage) {
  const sourceLanguage = cleanText(record.default_language || "en").slice(0, 2).toLowerCase();
  if (targetLanguage === sourceLanguage) {
    return {
      conditions: resolveField(record, "conditions"),
      allergies: resolveField(record, "allergies"),
      food_allergies: resolveField(record, "food_allergies"),
      medications: resolveField(record, "medications"),
      devices: resolveField(record, "devices"),
      notes: resolveField(record, "notes")
    };
  }

  const cacheKey = `${sourceLanguage}:${targetLanguage}:${record.public_slug || "demo"}`;
  if (state.translationCache[cacheKey]) {
    return state.translationCache[cacheKey];
  }

  const storedTranslation = readCachedJson(getFieldTranslationCacheKey(cacheKey));
  if (storedTranslation) {
    state.translationCache[cacheKey] = storedTranslation;
    return storedTranslation;
  }

  const sourceFields = {
    conditions: resolveField(record, "conditions"),
    allergies: resolveField(record, "allergies"),
    food_allergies: resolveField(record, "food_allergies"),
    medications: resolveField(record, "medications"),
    devices: resolveField(record, "devices"),
    notes: resolveField(record, "notes")
  };

  if (!config.translationFunctionName || !hasSupabaseConfig()) {
    return sourceFields;
  }

  try {
    const translated = await requestTranslation(sourceLanguage, targetLanguage, sourceFields);
    state.translationCache[cacheKey] = translated;
    writeCachedJson(getFieldTranslationCacheKey(cacheKey), translated);
    return translated;
  } catch (error) {
    console.warn("Public translation failed", error);
    return sourceFields;
  }
}

async function renderProfile() {
  const record = state.profile || demoProfile;
  const isPending = cleanText(record.workflow_status) === "pending";
  const translated = await translateFields(record, state.lang);

  pendingPanel?.classList.toggle("is-hidden", !isPending);
  profileGrid?.classList.toggle("is-hidden", isPending);

  const values = {
    name: cleanText(record.full_name) || "N/A",
    conditions: cleanText(translated.conditions) || "N/A",
    allergies: cleanText(translated.allergies) || "N/A",
    foodAllergies: cleanText(translated.food_allergies) || "N/A",
    medications: cleanText(translated.medications) || "N/A",
    devices: cleanText(translated.devices) || "N/A",
    bloodType: cleanText(record.blood_type) || "N/A",
    gender: formatGenderValue(record.gender, getCopy()),
    birthDate: formatBirthDate(record.birth_date),
    age: cleanText(record.age) || "N/A",
    weight: cleanText(record.weight) || "N/A",
    height: cleanText(record.height) || "N/A",
    organDonor: formatOrganDonorValue(record.organ_donor, getCopy()),
    doctor: cleanText(record.doctor) || "N/A",
    clinic: cleanText(record.clinic) || "N/A",
    insurance: cleanText(record.insurance) || "N/A",
    country: cleanText(record.country) || "N/A",
    stateRegion: cleanText(record.state_region) || "N/A",
    city: cleanText(record.city) || "N/A",
    postalCode: cleanText(record.postal_code) || "N/A",
    contact1Name: cleanText(record.emergency_contact_1_name),
    contact1Phone: formatPhone(record.emergency_contact_1_phone),
    contact2Name: cleanText(record.emergency_contact_2_name),
    contact2Phone: formatPhone(record.emergency_contact_2_phone)
  };

  fieldNodes.forEach((node) => {
    const mapped = values[node.dataset.field];
    node.textContent = mapped || "-";
  });

  const notes = cleanText(translated.notes)
    .split(/\r?\n+/)
    .map((item) => item.replace(/^[-*]\s*/, "").trim())
    .filter(Boolean);
  noteNodes.forEach((node) => {
    const index = Number(node.dataset.note);
    node.textContent = notes[index] || (index === 0 ? "-" : "");
  });

  callLink.href = values.contact1Phone ? `tel:${sanitizeTel(values.contact1Phone)}` : "#";
  contactCards.forEach((card, index) => {
    const phone = index === 0 ? values.contact1Phone : values.contact2Phone;
    card.href = phone ? `tel:${sanitizeTel(phone)}` : "#";
    card.classList.toggle("is-disabled", !phone);
  });

  const hasRecord = Boolean(cleanText(record.full_record_url));
  recordLink.classList.toggle("is-hidden", !hasRecord);
  if (hasRecord) {
    recordLink.href = record.full_record_url;
  }

  requestChangesLink?.toggleAttribute("disabled", false);

  if (isPending) {
    showStatus("warning", "statusPendingTitle", "statusPendingMessage");
  }

  document.title = `${values.name} | MyMedicalNFC.com`;
}

async function loadProfile() {
  state.identifier = detectIdentifier();
  if (!state.identifier) {
    document.body.classList.remove("profile-mode");
    overviewView.classList.remove("is-hidden");
    profileView.classList.add("is-hidden");
    requestChangesLink?.classList.add("is-hidden");
    hideStatusPopup();
    return;
  }

  overviewView.classList.add("is-hidden");
  profileView.classList.add("is-hidden");
  requestChangesLink?.classList.remove("is-hidden");
  document.body.classList.add("profile-mode");

  if (!hasSupabaseConfig()) {
    state.profile = demoProfile;
    await renderProfile();
    profileView.classList.remove("is-hidden");
    return;
  }

  try {
    const { data, error } = await getClient()
      .from(config.profilesReadTable || "medical_profiles_public")
      .select("*")
      .eq(config.lookupField || "public_slug", state.identifier)
      .maybeSingle();

    if (error || !data) {
      throw error || new Error("Profile not found");
    }

    state.profile = data;
    const explicitLanguage = new URL(window.location.href).searchParams.get("lang");
    if (!explicitLanguage) {
      const profileLanguage = cleanText(data.default_language || "en").slice(0, 2).toLowerCase();
      if (languageOptions[profileLanguage]) {
        state.lang = profileLanguage;
        root.lang = state.lang;
        applyCopy();
      }
    }
    hideStatusPopup();
    await renderProfile();
    profileView.classList.remove("is-hidden");
  } catch (error) {
    console.warn("Profile load failed", error);
    showStatus("error", "statusErrorTitle", "statusErrorMessage");
    state.profile = {
      public_slug: state.identifier,
      workflow_status: "archived",
      default_language: "en",
      full_name: "Medical profile"
    };
    await renderProfile();
    profileView.classList.remove("is-hidden");
  }
}

function getCurrentPosition() {
  return new Promise((resolve, reject) => {
    navigator.geolocation.getCurrentPosition(resolve, reject, {
      enableHighAccuracy: true,
      timeout: 12000,
      maximumAge: 0
    });
  });
}

async function handleShareLocation() {
  try {
    const position = await getCurrentPosition();
    const latitude = position.coords.latitude.toFixed(6);
    const longitude = position.coords.longitude.toFixed(6);
    const mapUrl = `https://maps.google.com/?q=${latitude},${longitude}`;

    if (navigator.share) {
      await navigator.share({ title: "Location", text: mapUrl, url: mapUrl });
    } else if (navigator.clipboard?.writeText) {
      await navigator.clipboard.writeText(mapUrl);
    } else {
      window.open(mapUrl, "_blank", "noopener");
    }

    flashStatus("success", "statusLocationCopiedTitle", "statusLocationCopiedMessage");
  } catch (error) {
    flashStatus("error", "statusLocationErrorTitle", "statusLocationErrorMessage");
  }
}

